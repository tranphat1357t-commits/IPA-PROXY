                    }
                    Link(destination: URL(string: "https://zalo.me/g/gjjxyw976")!) {
                        Label("Box Zalo", systemImage: "person.3.fill")
                    }
                }
            }
            .navigationTitle("Liên hệ")
            .navigationBarTitleDisplayMode(.inline)
        }
